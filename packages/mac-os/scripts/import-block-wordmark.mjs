#!/usr/bin/env node
// Imports the brand studio's block wordmark — the name spelt in the mark's
// construction — into the native shell as an SVG, drawn the way the studio
// exports its "Blocks" layout in the mono variant: black on nothing, no
// padding, the counters a fainter path under the ink. The shell paints it
// as a template, so only its shape crosses over. Re-run after changing the glyphs in the brand package's
// `mark.ts`:
//
//   node scripts/import-block-wordmark.mjs
import { writeFile } from "node:fs/promises";

const brand = new URL("../../brand/src/brand/", import.meta.url);
const output = new URL(
  "../Sources/Reviewer/Views/Chat/BlockWordmark.generated.swift",
  import.meta.url
);

const { DEFAULT_CONFIG, PRESETS } = await import(new URL("config.ts", brand));
const { buildScene } = await import(new URL("geometry.ts", brand));
const { renderSvg } = await import(new URL("svg.ts", brand));

const mono = PRESETS.find((preset) => preset.id === "mono");
const config = {
  ...DEFAULT_CONFIG,
  ...mono.config,
  layout: "blocks",
  markPadding: 0,
  canvasPadding: 0,
};
const scene = buildScene(config, null);
const svg = renderSvg(scene, config);

await writeFile(
  output,
  `// Generated by scripts/import-block-wordmark.mjs from the brand package's
// "Blocks" layout — do not edit; change the glyphs in
// packages/brand/src/brand/mark.ts and re-run the script.
import Foundation

enum BlockWordmarkArtwork {
    static let svg = ##"${svg}"##
    /// Width over height, so the wordmark can be sized by either.
    static let aspectRatio: CGFloat = ${scene.width / scene.height}
    /// Blocks across, so a block can be given a size in points.
    static let columns: CGFloat = ${scene.width / 100}
}
`
);
console.log(`wrote ${output.pathname}`);
