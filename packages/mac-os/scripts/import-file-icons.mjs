#!/usr/bin/env node
// Imports the web app's file-type icons into the native shell: @pierre/trees'
// built-in sprite (the "complete" set the SPA's tree uses), the rules that
// pick a symbol for a file name, and the SPA's own hue for each symbol, all
// written out as one Swift source so the sidebar resolves and paints an icon
// with nothing crossing the bridge. Re-run after bumping @pierre/trees or
// editing `file-type-hues.ts`:
//
//   node scripts/import-file-icons.mjs
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";

const spa = new URL("../../spa/", import.meta.url);
const trees = new URL("node_modules/@pierre/trees/", spa);
const output = new URL(
  "../Sources/Reviewer/FileIcons/PierreIcons.generated.swift",
  import.meta.url
);

const { getBuiltInSpriteSheet } = await import(
  pathToFileURL(fileURLToPath(new URL("dist/index.js", trees))).href
);
const { HUE, hueOf } = await import(
  pathToFileURL(
    fileURLToPath(new URL("src/components/ui/file-type-hues.ts", spa))
  ).href
);
const { version } = JSON.parse(
  await readFile(new URL("package.json", trees), "utf8")
);

// The rules are module-private in the package, so they are lifted out of its
// source: three object literals, each evaluated as the plain data it is.
const rulesSource = await readFile(
  new URL("dist/builtInIcons.js", trees),
  "utf8"
);
const table = (name) => {
  const match = rulesSource.match(
    new RegExp(`const ${name} = (\\{[\\s\\S]*?\\n\\});`)
  );
  if (match === null) throw new Error(`${name} not found in @pierre/trees`);
  return Function(`return ${match[1]}`)();
};
const byFileName = table("BUILT_IN_FILE_NAME_TOKENS");
const byExtension = table("BUILT_IN_FILE_EXTENSION_TOKENS");
const extensionOverrides = table("COMPLETE_EXTENSION_OVERRIDES");

const SYMBOL_PREFIX = "file-tree-builtin-";
const symbols = new Map();
const symbolPattern =
  /<symbol id="([^"]+)" viewBox="([^"]+)">([\s\S]*?)<\/symbol>/g;
for (const [, id, viewBox, body] of getBuiltInSpriteSheet("complete").matchAll(
  symbolPattern
)) {
  if (!id.startsWith(SYMBOL_PREFIX)) continue;
  symbols.set(id.slice(SYMBOL_PREFIX.length), {
    viewBox,
    body: body.replace(/\s+/g, " ").trim(),
  });
}
if (!symbols.has("default")) throw new Error("the sprite has no default icon");

const tokens = new Set([
  ...symbols.keys(),
  ...Object.values(byFileName),
  ...Object.values(byExtension),
  ...Object.values(extensionOverrides),
]);
for (const token of tokens) {
  if (!symbols.has(token)) throw new Error(`no symbol for token "${token}"`);
}

const swiftString = (text) => {
  if (text.includes('"#')) throw new Error(`cannot quote ${text}`);
  return `#"${text}"#`;
};
const stringTable = (entries) =>
  entries
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([key, value]) => `        ${swiftString(key)}: ${swiftString(value)},`)
    .join("\n");

const symbolLines = [...symbols]
  .sort(([a], [b]) => (a < b ? -1 : 1))
  .map(
    ([token, { viewBox, body }]) =>
      `        ${swiftString(token)}: Symbol(viewBox: ${swiftString(viewBox)}, body: ${swiftString(body)}),`
  )
  .join("\n");
const hueLines = [...symbols.keys()]
  .sort()
  .map((token) => {
    const [light, dark] = HUE[hueOf(token)];
    return `        ${swiftString(token)}: Hue(light: ${swiftString(light)}, dark: ${swiftString(dark)}),`;
  })
  .join("\n");

const swift = `// Generated by scripts/import-file-icons.mjs from @pierre/trees ${version}
// and the SPA's file-type-hues.ts — do not edit; re-run the script.
//
// The web tree's file-type icons: every symbol of the "complete" sprite as a
// standalone SVG body painting in currentColor, the rules that choose one for
// a file name, and the hue the SPA gives each in either palette.
enum PierreIcons {
    struct Symbol: Sendable {
        let viewBox: String
        let body: String
    }

    struct Hue: Sendable {
        let light: String
        let dark: String
    }

    static let symbols: [String: Symbol] = [
${symbolLines}
    ]

    static let hues: [String: Hue] = [
${hueLines}
    ]

    /// By the whole file name, lower-cased — \`.gitignore\`, \`dockerfile\`.
    static let byFileName: [String: String] = [
${stringTable(Object.entries(byFileName).map(([k, v]) => [k.toLowerCase(), v]))}
    ]

    /// By extension, longest candidate first — \`mdx.tsx\` before \`tsx\`.
    static let byExtension: [String: String] = [
${stringTable(Object.entries(byExtension).map(([k, v]) => [k.toLowerCase(), v]))}
    ]

    /// The complete set's own picks over the standard ones — React for tsx.
    static let extensionOverrides: [String: String] = [
${stringTable(Object.entries(extensionOverrides).map(([k, v]) => [k.toLowerCase(), v]))}
    ]
}
`;

await writeFile(output, swift);
console.log(
  `wrote ${fileURLToPath(output)}: ${symbols.size} symbols, ${Object.keys(byFileName).length} names, ${Object.keys(byExtension).length} extensions`
);
