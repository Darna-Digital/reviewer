// Imports the brand studio's block wordmark — the name spelt in the mark's
// construction, the same artwork the Mac app rests over a new chat — for the
// site's footer. It writes the two paths the studio's "Blocks" layout draws:
// the letters' ink and their counters, which are drawn fainter beneath.
// Re-run after changing the glyphs in the brand package's `mark.ts`:
//
//   node scripts/import-block-wordmark.ts
import { writeFile } from "node:fs/promises";

type Box = { x: number; y: number; width: number; height: number };

const brand = new URL("../../brand/src/brand/", import.meta.url);
const output = new URL(
  "../src/components/block-wordmark.generated.ts",
  import.meta.url
);

const { DEFAULT_CONFIG, PRESETS } = await import(
  new URL("config.ts", brand).href
);
const { buildScene } = await import(new URL("geometry.ts", brand).href);

const mono = PRESETS.find((preset: { id: string }) => preset.id === "mono");
const scene = buildScene(
  {
    ...DEFAULT_CONFIG,
    ...mono.config,
    layout: "blocks",
    markPadding: 0,
    canvasPadding: 0,
  },
  null
);

// The blocks are square cells on a 100-unit grid, so whole numbers suffice.
const path = (boxes: Array<Box>) =>
  boxes
    .map(
      ({ x, y, width, height }) =>
        `M${Math.round(x)} ${Math.round(y)}h${Math.round(width)}v${Math.round(height)}h${-Math.round(width)}Z`
    )
    .join("");

await writeFile(
  output,
  `// Generated by scripts/import-block-wordmark.ts from the brand package's
// "Blocks" layout — do not edit; change the glyphs in
// packages/brand/src/brand/mark.ts and re-run the script.
export const BLOCK_WORDMARK = {
  width: ${Math.round(scene.width)},
  height: ${Math.round(scene.height)},
  ink: "${path(scene.blocks)}",
  counters: "${path(scene.counters)}",
} as const;
`
);
console.log(`wrote ${output.pathname}`);
